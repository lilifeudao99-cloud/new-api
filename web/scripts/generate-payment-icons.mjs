import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { format } from 'oxfmt'

// react-icons exposes whole packs, not single-icon entrypoints. Extract only
// these existing payment logos so a dynamic pack lookup cannot pull the entire
// Simple Icons namespace into the wallet's blocking route dependencies.
const require = createRequire(import.meta.url)
const packPath = require.resolve('react-icons/si')
const source = readFileSync(packPath, 'utf8')
const license = readFileSync(
  path.join(path.dirname(packPath), '../LICENSE'),
  'utf8'
)
  .split('---')[0]
  .trim()
const header = `${readFileSync(fileURLToPath(import.meta.url), 'utf8').split('*/')[0]}*/\n`
const lines = [
  '// Generated by scripts/generate-payment-icons.mjs from the installed react-icons version.',
  '// Simple Icons artwork: CC0-1.0, https://github.com/simple-icons/simple-icons.',
  `/*! React Icons adapter license:\n${license}\n*/`,
  "import { GenIcon, type IconType } from 'react-icons'",
  '',
]
for (const name of ['SiAlipay', 'SiWechat', 'SiStripe']) {
  const match = source.match(
    new RegExp(
      `(?:export )?function ${name} \\(props\\) \\{\\s*return GenIcon\\((.+?)\\)\\(props\\);\\s*\\};`
    )
  )
  if (!match) {
    throw new Error(`Unsupported react-icons module format: ${name}`)
  }
  lines.push(
    `export const ${name}: IconType = GenIcon(${JSON.stringify(JSON.parse(match[1]))})`
  )
}
const target = new URL(
  '../src/components/payment-icons.gen.ts',
  import.meta.url
)
const config = JSON.parse(
  readFileSync(new URL('../.oxfmtrc.json', import.meta.url), 'utf8')
)
const formatted = await format(fileURLToPath(target), lines.join('\n'), config)
if (formatted.errors.length) throw new Error('Could not format payment icons')
const output = header + formatted.code
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error('Payment icons are stale; run bun run icons:generate')
  }
} else {
  writeFileSync(target, output)
}
