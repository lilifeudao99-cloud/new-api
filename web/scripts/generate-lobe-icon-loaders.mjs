import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { format } from 'oxfmt'

const require = createRequire(import.meta.url)
const root = path.dirname(require.resolve('@lobehub/icons/package.json'))
const toc = JSON.parse(readFileSync(path.join(root, 'es/toc.json'), 'utf8'))
const header = `${readFileSync(fileURLToPath(import.meta.url), 'utf8').split('*/')[0]}*/\n`
const lines = [
  '// Generated by scripts/generate-lobe-icon-loaders.mjs. Regenerate after updating @lobehub/icons.',
  '// Import individual variants so a basic logo never loads avatars, UI libraries, or other brands.',
  'export const lobeIconLoaders: Record<string, Record<string, () => Promise<{ default: unknown }>>> = {',
]

for (const icon of toc) {
  const source = readFileSync(
    path.join(root, 'es', icon.id, 'index.js'),
    'utf8'
  )
  const components = new Map(
    [...source.matchAll(/import (\w+) from "\.\/components\/([^"\n]+)";/g)].map(
      (match) => [match[1], match[2]]
    )
  )
  const variants = [['default', source.match(/var Icons = (\w+);/)?.[1]]]
  for (const match of source.matchAll(/Icons\.(\w+) = (\w+);/g)) {
    if (components.has(match[2])) variants.push([match[1], match[2]])
  }
  if (!variants[0][1] || !components.has(variants[0][1])) {
    throw new Error(`Unsupported icon module format: ${icon.id}`)
  }
  lines.push(`  ${icon.id}: {`)
  for (const [variant, component] of variants) {
    lines.push(
      `    ${variant}: () => import('@lobehub/icons/es/${icon.id}/components/${components.get(component)}'),`
    )
  }
  lines.push('  },')
}
lines.push(
  '}',
  '',
  'export const lobeIconNames = [',
  ...toc.flatMap((icon) => {
    const names = [icon.id]
    if (icon.param.hasColor) names.push(`${icon.id}.Color`)
    return names.map((name) => `  '${name}',`)
  }),
  ']',
  ''
)

const target = new URL('../src/lib/lobe-icon-loaders.gen.ts', import.meta.url)
const config = JSON.parse(
  readFileSync(new URL('../.oxfmtrc.json', import.meta.url), 'utf8')
)
const formatted = await format(fileURLToPath(target), lines.join('\n'), config)
if (formatted.errors.length > 0) {
  throw new Error('Could not format generated icon loaders')
}
const output = header + formatted.code
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error('Icon loaders are stale; run bun run icons:generate')
  }
} else {
  writeFileSync(target, output)
}
